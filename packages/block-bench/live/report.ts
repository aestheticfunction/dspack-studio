/** REPORT.md: a derived view of runs.jsonl and summary.json, regenerated, never edited. */
import type { Corpus } from "./corpus";
import type { EvaluationResult } from "./evaluate";
import type { ArmStats } from "./metrics";

const row = (cells: Array<string | number | null | undefined>) => `| ${cells.map((c) => (c === null || c === undefined ? "n/a" : String(c))).join(" | ")} |`;
const pct = (v: number | null | undefined) => (v === null || v === undefined ? "n/a" : `${(100 * v).toFixed(1)}%`);
const num = (v: number | null | undefined, digits = 0) => (v === null || v === undefined ? "n/a" : v.toFixed(digits));
const ms = (v: number | null | undefined) => (v === null || v === undefined ? "n/a" : `${Math.round(v)} ms`);

export function renderReport(result: EvaluationResult, context: { providerId: string; corpus: Corpus }): string {
  const { summary, preflight } = result;
  const out: string[] = [
    `# Interface-blocks live evaluation (Phase 1B): run ${result.runId}`,
    "",
    "Generated by `pnpm --filter @dspack-studio/block-bench eval:live` from runs.jsonl. Do not edit by hand.",
    "",
    `Provider: \`${context.providerId}\`. Corpus: \`${context.corpus.corpus}\` v${context.corpus.version}, frozen ${context.corpus.frozenAt}. Cells: ${result.cells.done} of ${result.cells.total} done (${result.cells.reused} reused from the log).${result.stopped ? ` Stopped: ${result.stopped.reason}: ${result.stopped.message}` : ""}`,
    "",
    `Preflight (${preflight.at}): ${preflight.baseUrl ? `deployed at ${preflight.baseUrl}, build id ${preflight.buildId ?? "unknown"}, Worker ${preflight.worker?.shape ?? "not probed"}, hosted models ${preflight.models?.join(", ") ?? "unknown"}.` : "no deployment probed (not a hosted run)."} Sidecars: ${preflight.sidecars.map((s) => `${s.reference} ${s.status}, binding ${s.binding}, usable ${s.usable.join(" ") || "none"}`).join("; ")}.`,
    "",
  ];
  if (preflight.drafts) out.push("**Provisional.** At least one sidecar in use is a draft. ADR-B3 counts approved sidecars only; these numbers inform the drafts, they do not graduate anything.", "");
  if (context.providerId === "fake:scripted") out.push("**Dry run.** The scripted provider calls no model: every figure that needs provider-reported usage reads n/a, and parity reflects the replayed worked examples, not generation.", "");
  out.push(
    "Tokens per success are provider-reported input plus output across every call of the run (planning included), over passing runs whose every call was metered. Pass rates exclude provider and policy failures, which are listed separately for re-running. Nothing here is estimated.",
    "",
  );

  out.push("## Decision (ADR-B3)", "");
  if (summary.decisions.length === 0) out.push("No fresh cells with all three arms yet.", "");
  for (const d of summary.decisions) {
    out.push(`### ${d.reference} on ${d.provider}: **${d.verdict}**`, "");
    out.push(row(["Arm", "Evaluated", "Pass rate", "Tokens per success"]), row(["---", "---:", "---:", "---:"]));
    for (const arm of ["block", "capped", "production"] as const) out.push(row([arm, d.evaluated[arm], pct(d.passRates[arm]), num(d.tokens[arm])]));
    out.push("", `Token reduction vs production: ${pct(d.tokens.reductionVsProduction)}; vs capped: ${pct(d.tokens.reductionVsCapped)}. Rule: at least ${100 * d.options.reduction}% fewer tokens per success and a pass rate within ${100 * d.options.margin} points of both primitive arms, with at least ${d.options.minimum} evaluated runs per arm.`, "");
    for (const reason of d.reasons) out.push(`- ${reason}`);
    out.push("");
  }

  const byRef = new Map<string, ArmStats[]>();
  for (const s of summary.arms) byRef.set(`${s.reference} on ${s.provider}`, [...(byRef.get(`${s.reference} on ${s.provider}`) ?? []), s]);
  for (const [title, stats] of byRef) {
    out.push(`## ${title}`, "");
    out.push("### Fresh builds", "");
    out.push(row(["Arm", "Cells", "Evaluated", "Passed", "Pass rate", "First attempt", "Repairs/success", "Tokens/success (metered n)", "Input", "Output", "Provider calls/run", "Request bytes/run", "p50 total", "p50 first gated", "p50 block phase", "Parity mean", "Re-run eligible"]));
    out.push(row(["---", "---:", "---:", "---:", "---:", "---:", "---:", "---:", "---:", "---:", "---:", "---:", "---:", "---:", "---:", "---:", "---:"]));
    for (const s of stats.filter((x) => x.condition === "fresh")) {
      out.push(
        row([
          s.arm,
          s.n,
          s.evaluated,
          s.passed,
          pct(s.passRate),
          pct(s.firstAttemptPassRate),
          num(s.repairsPerSuccess, 2),
          `${num(s.tokensPerSuccess)} (${s.meteredSuccesses})`,
          num(s.inputTokensPerSuccess),
          num(s.outputTokensPerSuccess),
          num(s.providerCallsPerRun, 2),
          num(s.requestBytesPerRun),
          ms(s.latency.totalMs),
          ms(s.latency.firstGatedAttemptMs),
          ms(s.latency.blockPhaseMs),
          pct(s.parity.meanScore),
          s.rerunEligible,
        ]),
      );
    }
    out.push("");
    const block = stats.find((x) => x.condition === "fresh" && x.arm === "block");
    if (block) {
      out.push("### Block arm, by path (ADR-B4 stratification)", "");
      out.push(row(["Path", "Runs", "Passed"]), row(["---", "---:", "---:"]));
      for (const [path, p] of Object.entries(block.paths)) out.push(row([path, p!.n, p!.passed]));
      out.push("", `Fallbacks by classification: ${Object.entries(block.fallbackByClassification).map(([k, v]) => `${k} ${v}`).join(", ") || "none"}. Budget remaining at fallback: ${Object.entries(block.budgetRemainingAtFallback).map(([k, v]) => `${k} left: ${v}`).join(", ") || "none"}. Invariant failures: ${block.invariantFailures}. Budget exhausted: ${block.budgetExhausted}.`, "");
    }
    const sel = summary.selection.find((x) => `${x.reference} on ${x.provider}` === title);
    if (sel) {
      out.push("### Selection accuracy (block arm, fresh)", "");
      out.push(row(["Prompts", "Accuracy", "Hit", "Missed to null", "Wrong block", "Null correct", "False block", "Explicit null", "Omitted", "Rejected", "Intent accuracy"]));
      out.push(row(["---:", "---:", "---:", "---:", "---:", "---:", "---:", "---:", "---:", "---:", "---:"]));
      out.push(row([sel.n, pct(sel.accuracy), sel.hit, sel.missedToNull, sel.wrongBlock, sel.nullCorrect, sel.falseBlock, sel.explicitNull, sel.omitted, sel.rejected, pct(sel.intentAccuracy)]), "");
    }
    const refinements = stats.filter((x) => x.condition !== "fresh");
    if (refinements.length > 0) {
      out.push("### Refinements (on each arm's own fresh result)", "");
      out.push(row(["Condition", "Arm", "Cells", "Skipped", "Evaluated", "Pass rate", "Changed", "Retention", "Tokens/success (metered n)", "Re-run eligible"]));
      out.push(row(["---", "---", "---:", "---:", "---:", "---:", "---:", "---:", "---:", "---:"]));
      for (const s of refinements) out.push(row([s.condition, s.arm, s.n, s.skipped, s.evaluated, pct(s.passRate), pct(s.changedRate), pct(s.retention), `${num(s.tokensPerSuccess)} (${s.meteredSuccesses})`, s.rerunEligible]));
      out.push("");
    }
    const failures = stats.filter((x) => x.rerunEligible > 0);
    if (failures.length > 0) {
      out.push("### Provider and policy failures (re-run symmetrically; not arm results)", "");
      out.push(row(["Condition", "Arm", "Provider", "Policy"]), row(["---", "---", "---:", "---:"]));
      for (const s of failures) out.push(row([s.condition, s.arm, s.rerunByKind.provider ?? 0, s.rerunByKind.policy ?? 0]));
      out.push("");
    }
  }
  out.push("## Not measured in this run", "", "- Named vs positional encoding: the block phase takes the named encoding only; the request sizes of both are measured offline in `packages/block-bench/results.json`.", "- Time to first valid preview equals completion today (ADR-B3) and is the p50 total above.", "");
  out.push(`Totals: ${summary.totals.records} records, ${summary.totals.completed} completed, ${summary.totals.providerCalls} provider calls, ${summary.totals.inputTokens} input and ${summary.totals.outputTokens} output tokens reported, ${summary.totals.requestBytes} request bytes.`, "");
  return `${out.join("\n")}`;
}
