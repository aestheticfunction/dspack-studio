/** The authoring walkthrough in a real browser, with screenshots. Usage: node walk.cjs <url> <dir> [dpr] */
const { chromium } = require("playwright");
const [url, out, dpr = "1"] = process.argv.slice(2);
const DISMISSED = JSON.stringify({ schema: "composer.experimental.workspace/onboarding", version: 1, data: { dismissed: true } });
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 1280, height: 800 }, deviceScaleFactor: Number(dpr) });
  const p = await ctx.newPage();
  const errors = []; p.on("pageerror", (e) => errors.push(String(e))); p.on("console", (m) => m.type() === "error" && errors.push(m.text()));
  await p.addInitScript((v) => { if (!sessionStorage.getItem("s")) { localStorage.setItem("composer.experimental.workspace.onboarding", v); sessionStorage.setItem("s", "1"); } }, DISMISSED);
  await p.route("**/api/**", (r) => r.fulfill({ status: 503, body: '{"error":"unavailable"}' }));
  await p.goto(url); await p.getByTestId("nav-library").click();
  await p.waitForSelector('[data-testid="check-pill"]:not([data-state="loading"])');
  let n = 0; const shot = async (name) => { await p.waitForTimeout(350); await p.screenshot({ path: `${out}/${String(++n).padStart(2, "0")}-${name}.png` }); };
  await p.getByTestId("library-item-hotel-search").click(); await shot("approved-hotel-search");
  await p.getByTestId("create-draft").click(); await shot("draft-created");
  await p.getByTestId("tab-examples").click();
  await p.getByTestId("example-invalid").click(); await shot("examples-tab");
  await p.getByTestId("data-errors-0").fill("");
  await shot("example-modified-empty-error");
  await p.getByTestId("run-checks").click(); await p.waitForSelector('[data-testid="authoring-bar"][data-state="fail"]');
  await p.getByTestId("tab-checks").click(); await shot("checks-fail");
  await p.getByTestId("edit-example-invalid").click();
  await p.getByTestId("data-errors-0").fill("Choose a check-out date after check-in."); await shot("example-corrected");
  await p.getByTestId("run-checks").click(); await p.waitForSelector('[data-testid="authoring-bar"][data-state="pass"]'); await shot("checks-pass");
  await p.getByTestId("approve").click(); await shot("approve-confirm");
  await p.getByTestId("approve-confirm-button").click(); await p.waitForSelector('[data-testid="authoring-notice"]'); await shot("approved");
  await p.reload(); await p.waitForSelector('[data-testid="check-pill"]:not([data-state="loading"])');
  if ((await p.getByTestId("composition-library").getAttribute("data-library")) !== "open") await p.getByTestId("toggle-library").click();
  await p.getByTestId("library-item-hotel-search").click();
  await p.getByRole("radio", { name: /v2 Approved/i }).check(); await p.getByTestId("scenario-invalid").click();
  await shot("after-reload-library");
  await p.getByTestId("toggle-inspector").click(); await shot("after-reload-versions");
  // The phone: the same draft, edited in the inspector sheet.
  const phone = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: Number(dpr) });
  const q = await phone.newPage();
  await q.addInitScript((v) => localStorage.setItem("composer.experimental.workspace.onboarding", v), DISMISSED);
  await q.route("**/api/**", (r) => r.fulfill({ status: 503, body: '{"error":"unavailable"}' }));
  await q.goto(url); await q.getByTestId("nav-library").click(); await q.waitForSelector('[data-testid="check-pill"]:not([data-state="loading"])');
  await q.getByRole("radio", { name: /v2 Draft/i }).check(); await q.waitForTimeout(300);
  await q.screenshot({ path: `${out}/${String(++n).padStart(2, "0")}-phone-draft.png` });
  await q.getByTestId("toggle-inspector").click(); await q.getByTestId("tab-examples").click(); await q.getByTestId("example-two").click();
  await q.getByTestId("data-hotels-1-remove").click(); await q.waitForTimeout(300);
  await q.screenshot({ path: `${out}/${String(++n).padStart(2, "0")}-phone-example-edit.png` });
  await q.getByTestId("run-checks").click(); await q.waitForSelector('[data-testid="authoring-bar"][data-state="fail"]'); await q.getByTestId("tab-checks").click(); await q.waitForTimeout(300);
  await q.screenshot({ path: `${out}/${String(++n).padStart(2, "0")}-phone-checks-fail.png` });
  console.log(JSON.stringify({ errors, versions: await p.getByTestId("versions").innerText().catch(() => "") }, null, 1));
  await b.close();
})();
